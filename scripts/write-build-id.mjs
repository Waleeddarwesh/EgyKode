#!/usr/bin/env node
/**
 * Stamp the build so a tab can tell when it has gone stale.
 *
 * A page left open across a deploy is running JavaScript from the previous
 * build while the CDN serves the new one. Next's client router then fetches an
 * RSC payload whose build id does not match, and navigation stops working:
 * scrolling still scrolls, links do nothing, and only a refresh recovers. This
 * site deployed eleven times in one day, so that window is not theoretical —
 * it produced a real report of a "frozen" page, and earlier the same mismatch
 * dumped a reader onto /en/labs/index.txt.
 *
 * Two artifacts, deliberately:
 *   public/build-id.txt   fetched at runtime to see what is deployed NOW
 *   lib/build-id.ts       compiled into the bundle: what this tab loaded
 *
 * They are written together, so they can only disagree when the tab is stale.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// The commit is the truthful identity in CI. Locally there is no deploy to be
// stale against, so a timestamp is enough to keep the two files consistent.
const id = (process.env.GITHUB_SHA ?? `local-${Date.now()}`).slice(0, 40);

const publicDir = join("apps", "web", "public");
mkdirSync(publicDir, { recursive: true });
writeFileSync(join(publicDir, "build-id.txt"), id, "utf8");

writeFileSync(
  join("apps", "web", "lib", "build-id.ts"),
  `// Generated by scripts/write-build-id.mjs — do not edit.\n` +
    `// Compared against /build-id.txt at runtime to detect a tab left open\n` +
    `// across a deploy. See components/layout/stale-build-guard.tsx.\n` +
    `export const BUILD_ID = ${JSON.stringify(id)};\n`,
  "utf8",
);

console.log(`build id: ${id}`);
